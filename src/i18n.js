const KEY = 'payprism-lang';

function stored() {
  try { return localStorage.getItem(KEY); } catch { return null; }
}

let lang = stored() || ((navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en');
if (!strings[lang]) lang = 'en';

export function getLang() { return lang; }

export function setLang(next) {
  if (!strings[next]) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* private mode: keep it for this visit only */ }
  document.documentElement.lang = next;
}

export function t(key, vars = {}) {
  const template = strings[lang][key] ?? strings.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_m, name) => (vars[name] ?? ''));
}

export function fmtNumber(value, digits = 2) {
  return new Intl.NumberFormat(lang === 'de' ? 'de-DE' : 'en-US', {
    minimumFractionDigits: 0, maximumFractionDigits: digits,
  }).format(value);
}
